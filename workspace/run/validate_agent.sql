-- OBJECT: AGENT pipeline acceptance checks
-- PURPOSE: Validate the September then October scenario for LAB-101
-- RUN: After both monthly loads in a fresh sandbox; each CHECK_NAME should show PASS
SELECT 'history_versions' AS CHECK_NAME,
       IFF(COUNT(*) = 5, 'PASS', 'FAIL') AS RESULT
FROM HISTORY.HIST_AGENT
UNION ALL
SELECT 'current_versions', IFF(COUNT(*) = 4, 'PASS', 'FAIL')
FROM HISTORY.HIST_AGENT WHERE CURRENT_IND = 'Y'
UNION ALL
SELECT 'september_snapshot', IFF(COUNT(*) = 3, 'PASS', 'FAIL')
FROM PROCESSING.PRC_AGENT WHERE VALUATION_DATE = '2026-09-30'
UNION ALL
SELECT 'october_snapshot', IFF(COUNT(*) = 4, 'PASS', 'FAIL')
FROM PROCESSING.PRC_AGENT WHERE VALUATION_DATE = '2026-10-31'
UNION ALL
SELECT 'missing_agent_retained', IFF(COUNT(*) = 1, 'PASS', 'FAIL')
FROM HISTORY.HIST_AGENT
WHERE AGENT_ID = 'A003' AND CURRENT_IND = 'Y' AND BEGIN_EFFECTIVE_DATE = '2026-09-30'
UNION ALL
SELECT 'old_a002_closed', IFF(COUNT(*) = 1, 'PASS', 'FAIL')
FROM HISTORY.HIST_AGENT
WHERE AGENT_ID = 'A002' AND CURRENT_IND = 'N'
  AND BEGIN_EFFECTIVE_DATE = '2026-09-30' AND END_EFFECTIVE_DATE = '2026-10-30'
UNION ALL
SELECT 'masking', IFF(COALESCE(COUNT_IF(AGENT_NAME <> '***MASKED***'
    OR (AGENT_EMAIL IS NOT NULL AND AGENT_EMAIL <> '***MASKED***')), 0) = 0, 'PASS', 'FAIL')
FROM PROCESSING.PRC_AGENT;

WITH expected AS (
    SELECT COLUMN1 AS AGENT_ID FROM VALUES ('A001'), ('A002'), ('A003'), ('A004')
), current_counts AS (
    SELECT AGENT_ID, COUNT(*) AS VERSION_COUNT FROM HISTORY.HIST_AGENT
    WHERE CURRENT_IND = 'Y' GROUP BY AGENT_ID
)
SELECT COALESCE(expected.AGENT_ID, current_counts.AGENT_ID) AS BAD_AGENT_ID,
       COALESCE(current_counts.VERSION_COUNT, 0) AS CURRENT_ROWS
FROM expected FULL OUTER JOIN current_counts ON expected.AGENT_ID = current_counts.AGENT_ID
WHERE expected.AGENT_ID IS NULL OR COALESCE(current_counts.VERSION_COUNT, 0) <> 1;

SELECT PROC_NAME, STATUS, ROW_COUNT, MESSAGE, RUN_TS
FROM ETL.LOAD_AUDIT ORDER BY AUDIT_ID DESC;

SELECT JOB_UUID, PROC_NAME, LOG_LEVEL, LOG_SECTION, LOG_TEXT
FROM PROCESSING_LOG.JOB_LOG ORDER BY LOG_TS DESC;